(() => {
  const profiles = {
    balanced: { label: "Balanced Portfolio", priors: { sn: 1.0, cagr: 1.0, trend: 1.1, mom: 0.9 }, risk: 0.02, ambitionCap: 0.18 },
    seasonal: { label: "Seasonal Heavy", priors: { sn: 1.25, cagr: 0.95, trend: 1.2, mom: 0.7 }, risk: 0.03, ambitionCap: 0.17 },
    volatile: { label: "New Product Volatility", priors: { sn: 0.9, cagr: 0.8, trend: 0.95, mom: 1.35 }, risk: 0.06, ambitionCap: 0.14 },
    recurring: { label: "Recurring Revenue Heavy", priors: { sn: 0.8, cagr: 1.2, trend: 1.25, mom: 0.75 }, risk: 0.015, ambitionCap: 0.2 }
  };

  const state = { years: [2021, 2022, 2023, 2024, 2025], vals: {}, charts: { f: null, s: null, l: null }, lastRun: null };

  const utils = window.CoreUtils;
  const dataModel = window.DataModel;
  const forecastEngine = window.ForecastEngine;
  const uiRender = window.UiRender;
  const targetPolicy = window.TargetPolicy;

  if (!utils || !dataModel || !forecastEngine || !uiRender || !targetPolicy) {
    throw new Error("AppController missing dependency. Verify script order in index.html.");
  }

  function banner(type, text) {
    const bannerNode = document.getElementById("banner");
    bannerNode.className = "banner " + type;
    bannerNode.textContent = text;
  }

  function esc(text) {
    return String(text ?? "").replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
  }

  function buildSlideNotes(pack) {
    const { clientName, targetYear, targetQuarter, result, controls, diagnostic, utils, currency } = pack;
    return [
      `${clientName} | ${targetYear} Q${targetQuarter} Target Pack`,
      "",
      `Target ladder (${currency}):`,
      `- Minimum: ${utils.money(result.min, currency)} (${utils.fmtPct(result.minYoY, 1)} YoY)`,
      `- Commit: ${utils.money(result.commit, currency)} (${utils.fmtPct(result.commitYoY, 1)} YoY)`,
      `- Stretch: ${utils.money(result.stretch, currency)} (${utils.fmtPct(result.stretchYoY, 1)} YoY)`,
      "",
      "Commercial assumptions:",
      `- Win rate: ${(controls.winRate * 100).toFixed(1)}%`,
      `- Pipeline: ${utils.money(controls.pipeline, currency)}`,
      `- Capacity factor: ${(controls.capacityFactor * 100).toFixed(0)}%`,
      `- Average deal value: ${utils.money(controls.dealValue, currency)}`,
      "",
      "Rationale:",
      `- Deseasonalized annual trend: ${utils.fmtPct(result.annTrend, 1)}`,
      `- Confidence: ${Math.round(result.confidence)}%`,
      `- Backtest sMAPE: ${(result.esm * 100).toFixed(1)}%`,
      `- Data quality score: ${Math.round(diagnostic.score)}/100`
    ].join("\n");
  }

  function exportMeetingPack() {
    if (!state.lastRun) {
      banner("warn", "Run the target engine first, then export the meeting pack.");
      return;
    }

    const pack = state.lastRun;
    const {
      clientName,
      targetYear,
      targetQuarter,
      result,
      controls,
      diagnostic,
      profile,
      currency
    } = pack;

    const slideNotes = buildSlideNotes(pack);
    if (navigator.clipboard?.writeText) {
      navigator.clipboard.writeText(slideNotes).catch(() => {});
    }

    const popup = window.open("", "_blank", "noopener,noreferrer");
    if (!popup) {
      banner("bad", "Popup blocked. Allow popups to export meeting pack.");
      return;
    }

    const warnings = diagnostic.warnings.length
      ? `<ul>${diagnostic.warnings.map((line) => `<li>${esc(line)}</li>`).join("")}</ul>`
      : "<p>None.</p>";

    popup.document.write(`<!doctype html>
<html><head><meta charset="utf-8"><title>${esc(clientName)} ${targetYear} Q${targetQuarter} Meeting Pack</title>
<style>
body{font-family:Segoe UI,Arial,sans-serif;color:#123137;padding:18px;line-height:1.4}
h1,h2{margin:0 0 8px} .meta{color:#3b5358;font-size:13px;margin-bottom:16px}
.grid{display:grid;grid-template-columns:1fr 1fr;gap:10px}.card{border:1px solid #d6e4e1;border-radius:10px;padding:10px}
table{width:100%;border-collapse:collapse} th,td{border-bottom:1px solid #e3ecea;padding:6px;text-align:left;font-size:13px}
.k{font-size:20px;font-weight:700}.s{font-size:12px;color:#4c666b}
</style></head><body>
<h1>${esc(clientName)} ${targetYear} Q${targetQuarter} - Target Setting Meeting Pack</h1>
<div class="meta">Generated by Commercial Target Studio. Currency: ${currency}. Profile: ${esc(profile.label)}.</div>
<div class="grid">
<div class="card"><h2>Target Ladder</h2>
<div class="k">${pack.utils.money(result.min, currency)}</div><div class="s">Minimum (${pack.utils.fmtPct(result.minYoY, 1)} YoY)</div>
<div class="k">${pack.utils.money(result.commit, currency)}</div><div class="s">Commit (${pack.utils.fmtPct(result.commitYoY, 1)} YoY)</div>
<div class="k">${pack.utils.money(result.stretch, currency)}</div><div class="s">Stretch (${pack.utils.fmtPct(result.stretchYoY, 1)} YoY)</div>
</div>
<div class="card"><h2>Reliability</h2>
<p>Confidence: <strong>${Math.round(result.confidence)}%</strong></p>
<p>Backtest sMAPE: <strong>${(result.esm * 100).toFixed(1)}%</strong></p>
<p>Data quality score: <strong>${Math.round(diagnostic.score)}/100</strong></p>
</div>
</div>
<div class="card" style="margin-top:10px"><h2>Commercial Assumptions</h2>
<table><tbody>
<tr><th>Win Rate</th><td>${(controls.winRate * 100).toFixed(1)}%</td></tr>
<tr><th>Capacity Factor</th><td>${(controls.capacityFactor * 100).toFixed(0)}%</td></tr>
<tr><th>Pipeline</th><td>${pack.utils.money(controls.pipeline, currency)}</td></tr>
<tr><th>Average Deal Value</th><td>${pack.utils.money(controls.dealValue, currency)}</td></tr>
</tbody></table></div>
<div class="card" style="margin-top:10px"><h2>Rationale & Diagnostics</h2>
<p>Trend: ${pack.utils.fmtPct(result.annTrend, 1)} annualized deseasonalized trajectory. Seasonality target index ${(result.targetSI * 100).toFixed(1)}.</p>
<p>Coverage: required pipeline ${pack.utils.money(result.reqPipeline, currency)}, current coverage ${pack.utils.fmtPct(result.coverage - 1, 1)}.</p>
<h3>Warnings</h3>${warnings}
<h3>Slide Notes (also copied to clipboard)</h3><pre>${esc(slideNotes)}</pre>
</div>
</body></html>`);
    popup.document.close();
    setTimeout(() => popup.print(), 250);
    banner("ok", "Meeting pack opened. Save as PDF from print dialog. Slide notes copied to clipboard.");
  }

  function run() {
    const arr = dataModel.series(state, utils.parseNumber, utils.toTime);
    const diagnostic = dataModel.diagnostics(state, arr, utils);
    uiRender.renderDiagnostics(diagnostic);
    if (diagnostic.errors.length) {
      banner("bad", diagnostic.errors[0]);
      return;
    }

    const targetYear = utils.parseNumber(document.getElementById("targetYear").value);
    const targetQuarter = Number(document.getElementById("targetQuarter").value);
    if (!Number.isFinite(targetYear) || targetYear < 2020) {
      banner("bad", "Invalid target year.");
      return;
    }

    const currency = "EUR";
    const profile = profiles[document.getElementById("profile").value] || profiles.balanced;
    const ambition = utils.clamp(utils.pct(document.getElementById("ambition").value), 0, profile.ambitionCap);
    const winRate = utils.clamp(utils.pct(document.getElementById("winRate").value), 0.01, 0.95);
    const capacityFactor = utils.clamp(utils.pct(document.getElementById("capacity").value), 0.6, 1.4);
    const pipeline = Math.max(utils.parseNumber(document.getElementById("pipeline").value) || 0, 0);
    const dealValue = Math.max(utils.parseNumber(document.getElementById("dealValue").value) || 1, 1);
    const clientName = (document.getElementById("clientName").value || "Client").trim();

    const calculated = targetPolicy.calculate({
      arr,
      targetYear,
      targetQuarter,
      profile,
      controls: { ambition, winRate, capacityFactor, pipeline, dealValue },
      forecastEngine,
      dataModel,
      utils
    });

    const result = calculated.result;

    uiRender.renderKpi(result, currency, { money: utils.money, fmtPct: utils.fmtPct });
    uiRender.plotForecast(state, arr, calculated.fittedSeries, `${targetYear} Q${targetQuarter}`, result.p, result.commit, currency, { money: utils.money });
    uiRender.plotSeason(state, calculated.seasonIndex, targetQuarter);
    uiRender.plotLadder(state, result.min, result.commit, result.stretch, calculated.commercialCapacity, currency, { money: utils.money });
    uiRender.renderInsights(result, currency, { fmtPct: utils.fmtPct, money: utils.money, qName: utils.qName });
    uiRender.renderMethods(result, profile, { fmtPct: utils.fmtPct });

    state.lastRun = {
      clientName,
      targetYear,
      targetQuarter,
      profile,
      result,
      controls: { ambition, winRate, capacityFactor, pipeline, dealValue },
      diagnostic,
      utils,
      currency
    };

    const qualityNote = diagnostic.warnings.length ? ` Data warnings: ${diagnostic.warnings.length}.` : "";
    banner("ok", `${clientName} ${targetYear} Q${targetQuarter}: commit ${utils.money(result.commit, currency)} (${utils.fmtPct(result.commitYoY, 1)} YoY), stretch ${utils.money(result.stretch, currency)} (${utils.fmtPct(result.stretchYoY, 1)} YoY). Required pipeline for commit: ${utils.money(result.reqPipeline, currency)}.${qualityNote}`);
  }

  function loadDemo() {
    state.vals = {
      "2021-Q1": 420000, "2021-Q2": 455000, "2021-Q3": 505000, "2021-Q4": 630000,
      "2022-Q1": 468000, "2022-Q2": 515000, "2022-Q3": 574000, "2022-Q4": 705000,
      "2023-Q1": 516000, "2023-Q2": 562000, "2023-Q3": 642000, "2023-Q4": 782000,
      "2024-Q1": 561000, "2024-Q2": 618000, "2024-Q3": 702000, "2024-Q4": 846000,
      "2025-Q1": 619000, "2025-Q2": 688000, "2025-Q3": 766000, "2025-Q4": 914000
    };
    dataModel.drawRows(state);
    banner("ok", "Demo data loaded.");
  }

  function init() {
    if (window.Chart && window.ChartDataLabels) {
      window.Chart.register(window.ChartDataLabels);
    }

    document.getElementById("targetYear").value = String(new Date().getFullYear() + 1);
    dataModel.drawRows(state);
    document.getElementById("ambition").addEventListener("input", (event) => {
      document.getElementById("ambitionLabel").textContent = event.target.value + "%";
    });
    document.getElementById("addPast").addEventListener("click", () => {
      state.years.push(Math.min(...state.years) - 1);
      dataModel.drawRows(state);
    });
    document.getElementById("addYear").addEventListener("click", () => {
      state.years.push(Math.max(...state.years) + 1);
      dataModel.drawRows(state);
    });
    document.getElementById("dropYear").addEventListener("click", () => {
      if (state.years.length <= 3) return;
      const year = Math.max(...state.years);
      state.years = state.years.filter((value) => value !== year);
      [1, 2, 3, 4].forEach((quarter) => delete state.vals[`${year}-Q${quarter}`]);
      dataModel.drawRows(state);
    });
    document.getElementById("run").addEventListener("click", run);
    document.getElementById("exportPack").addEventListener("click", exportMeetingPack);
    document.getElementById("demo").addEventListener("click", () => {
      loadDemo();
      run();
    });
    document.getElementById("clear").addEventListener("click", () => {
      state.vals = {};
      dataModel.drawRows(state);
      banner("warn", "All values cleared.");
    });
    loadDemo();
    run();
  }

  window.AppController = { init };
})();
